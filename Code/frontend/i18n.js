function changeLanguage(langKey) {
  const dict = i18nData[langKey] || i18nData.en;
  localStorage.setItem('mv_lang', langKey);

  // Toggle RTL for Arabic
  if (langKey === 'ar') {
    document.documentElement.setAttribute('dir', 'rtl');
    document.documentElement.setAttribute('lang', 'ar');
  } else {
    document.documentElement.removeAttribute('dir');
    document.documentElement.setAttribute('lang', langKey);
  }

  // Update translatable data-i18n attributes
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = dict[key];
      } else {
        el.innerText = dict[key];
      }
    }
  });
}

// Auto-load saved language or default to English
document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('mv_lang') || 'en';
  const langSelect = document.getElementById('langSelect');
  if (langSelect) {
    langSelect.value = savedLang;
  }
  changeLanguage(savedLang);
});
